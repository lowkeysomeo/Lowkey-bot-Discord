const assert=require('node:assert/strict');
process.env.DB_PATH=':memory:';
const {Collection,PermissionsBitField:P}=require('discord.js');
const {getDb}=require('../utils/database');
const {saveOptions}=require('../utils/customization');
const {validateCustomization}=require('../dashboard/customization');
const system=require('../utils/inviteSystem');
async function main(){
  const sent=[],actions=[];
  let uses=0,failRemove=false,failSend=false;
  const roles=new Collection(['r50','r100'].map(id=>[id,{id,managed:false,permissions:new P(0n)}]));
  const cache=new Collection();
  const member={id:'owner',user:{bot:false},roles:{cache,add:async id=>{actions.push('add:'+id);cache.set(id,{});},remove:async id=>{if(failRemove)throw Error('Tạm lỗi');actions.push('remove:'+id);cache.delete(id);}}};
  const me={permissions:new P(P.All),roles:{highest:{comparePositionTo:()=>1}}};
  const channel={id:'channel',guildId:'g',type:0,permissionsFor:()=>({has:()=>true}),send:async payload=>{if(failSend)throw Error('Lỗi mạng');sent.push(payload);}};
  const guild={id:'g',name:'Test',invites:{fetch:async()=>new Collection([['code',{code:'code',uses,inviter:{id:'owner',bot:false}}]])},
    members:{me,fetch:async id=>id?member:new Collection([['existing',{id:'existing'}]])},roles:{fetch:async id=>roles.get(id)},channels:{fetch:async()=>channel}};
  saveOptions('g',{inviteEnabled:true,inviteChannel:'channel',inviteRole50:'r50',inviteRole100:'r100'});
  await system.prime(guild);
  uses=1;
  await system.processBatch(guild,[{id:'new',user:{bot:false}}]);
  assert.equal(system.count('g','owner'),1);
  assert(sent[0].embeds[0].toJSON().description.includes('<@owner>'));
  assert.deepEqual(sent[0].allowedMentions,{parse:[],users:[],roles:[]});
  uses=2;await system.processBatch(guild,[{id:'new',user:{bot:false}}]);
  assert.equal(system.count('g','owner'),1,'Vào lại không được cộng thêm');
  uses=3;await system.processBatch(guild,[{id:'existing',user:{bot:false}}]);
  assert.equal(system.count('g','owner'),1,'Thành viên trước lúc bật không được tính lại');
  uses=4;await system.processBatch(guild,[{id:'robot',user:{bot:true}}]);
  uses=5;await system.processBatch(guild,[{id:'owner',user:{bot:false}}]);
  assert.equal(system.count('g','owner'),1);
  const before=new Map([['a',{uses:0,inviter:'A'}],['b',{uses:0,inviter:'B'}]]);
  assert.equal(system.attribute(before,new Map([['a',{uses:1,inviter:'A'}],['b',{uses:1,inviter:'B'}]]),2),null);
  assert.equal(system.attribute(before,new Map([['a',{uses:2,inviter:'A'}],['b',{uses:0,inviter:'B'}]]),2),'A');
  assert.equal(system.attribute(undefined,before,1),null);
  assert.equal(system.attribute(before,new Map([['new',{uses:1,inviter:'A'}]]),1),null);
  assert.equal(system.attribute(before,new Map(),1),null,'Link dùng một lần đã mất không được đoán');
  for(let n=0;n<49;n++)system.record('g','member'+n,'owner');
  assert.equal(system.count('g','owner'),50);
  await system.reward(guild,'owner');assert(cache.has('r50'));
  for(let n=49;n<99;n++)system.record('g','member'+n,'owner');
  failRemove=true;await assert.rejects(system.reward(guild,'owner'));failRemove=false;
  await system.reward(guild,'owner');assert(cache.has('r100'));assert(!cache.has('r50'));
  assert(actions.indexOf('add:r100')<actions.indexOf('remove:r50'));
  const previous=actions.length;await system.reward(guild,'owner');assert.equal(actions.length,previous);
  assert.equal(system.count('other','owner'),0);
  uses=6;failSend=true;await system.processBatch(guild,[{id:'retry',user:{bot:false}}]);failSend=false;
  const row=getDb().prepare('SELECT * FROM invite_members WHERE member_id=?').get('retry');assert.equal(row.notified,0);
  await system.announce(guild,row);assert.equal(getDb().prepare('SELECT notified FROM invite_members WHERE member_id=?').get('retry').notified,1);
  delete require.cache[require.resolve('../utils/inviteSystem')];
  assert.equal(require('../utils/inviteSystem').count('g','owner'),101,'Số lượt đọc lại từ SQLite');
  const validate=options=>validateCustomization({options},guild,new Collection([['channel',channel]]),roles,me);
  assert.throws(()=>validate({inviteRole100:'r50'}));
  assert.throws(()=>validate({inviteRole100:'foreign'}));
  assert.throws(()=>validate({inviteChannel:''}));
  roles.get('r100').permissions=new P(P.Flags.Administrator);
  assert.throws(()=>validate({inviteRole100:'r100'}));
  saveOptions('g',{inviteEnabled:false});uses=7;await system.processBatch(guild,[{id:'disabled',user:{bot:false}}]);
  assert.equal(system.count('g','owner'),101);
  console.log('Đạt: invite thường, không đoán lượt mơ hồ, chống vào lại/bot/tự mời, dữ liệu SQLite, 50→100 chỉ giữ role cao nhất, thử lại và kiểm tra cấu hình.');
  let failPrime=true, primeCalls=0;
  const recovery={...guild,id:'recovery',members:{...guild.members,fetch:async()=>{primeCalls++;if(failPrime)throw Error('Rate limited');return new Collection();}}};
  saveOptions('recovery',{inviteEnabled:true,inviteChannel:'channel'});
  await assert.rejects(system.prime(recovery));
  await system.processBatch(recovery,[{id:'during-startup',user:{bot:false}}]);
  assert.equal(system.count('recovery','owner'),0);
  failPrime=false;await system.tick({guilds:{cache:new Collection([['recovery',recovery]])}});
  assert.equal(primeCalls,2,'Tự thử lại dữ liệu ban đầu sau khi Discord giới hạn');
  getDb().close();
}
main().catch(e=>{console.error(e);process.exitCode=1;});
